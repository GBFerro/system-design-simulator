#!/usr/bin/env bash
# Proves every sensor in both directions (blocks what it must, allows what it must) against a
# throwaway git repository with its own factory.config.sh. A sensor with no case here is a sensor
# you only think protects you. Cases named after a bypass or a surviving mutation keep it dead.
# Usage: bash sensors/test.sh        Exit 0 when every case passes.
set -u
# Inside a git hook (pre-commit runs this suite), git exports GIT_INDEX_FILE, GIT_DIR and friends.
# Left set, every git call on the sandbox below would write into the real repository's index.
unset GIT_DIR GIT_INDEX_FILE GIT_WORK_TREE GIT_OBJECT_DIRECTORY GIT_ALTERNATE_OBJECT_DIRECTORIES \
  GIT_COMMON_DIR GIT_PREFIX GIT_NAMESPACE

here="$(cd "$(dirname "$0")" && pwd)"
sandbox="$(mktemp -d)"
trap 'rm -rf "$sandbox"' EXIT
pass=0
fail=0

# Paths as the agent's tools would send them (Windows form under Git Bash).
native() { if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi; }
json_str() {
  local s="${1//\\/\\\\}"
  s="${s//\"/\\\"}"
  s="${s//$'\n'/\\n}"
  s="${s//$'\t'/\\t}"
  printf '"%s"' "$s"
}

repo="$sandbox/repo"
git init -q -b main "$repo" 2>/dev/null || { git init -q "$repo" && git -C "$repo" checkout -q -b main; }
git -C "$repo" config user.email test@example.com
git -C "$repo" config user.name test
git -C "$repo" config commit.gpgsign false
# write_config <lint cmd> [format cmd] [stop checks]
write_config() {
  cat >"$repo/factory.config.sh" <<EOF
FACTORY_PROTECTED_BRANCHES='main'
FACTORY_LINT_CMD='$1'
FACTORY_FORMAT_CHECK_CMD='${2:-true}'
FACTORY_TYPECHECK_CMD='none'
FACTORY_TEST_CMD='true'
FACTORY_STOP_CHECKS="${3:-lint format}"
FACTORY_SOURCE_GLOBS='src/*.ts'
FACTORY_TEST_GLOBS='*.test.ts *.spec.ts'
FACTORY_TEST_CANDIDATES='{dir}/{name}.test.ts {dir}/__tests__/{name}.test.ts {dir}/{name}.spec.{ext} tests/**/{name}Spec.ts'
EOF
}
write_config true
mkdir -p "$repo/src" "$repo/sensors"
echo "# readme" >"$repo/README.md"
echo "export const a = 1" >"$repo/src/has.ts"
echo "test" >"$repo/src/has.test.ts"
printf 'src/gen/*  # generated by the build\nsrc/raw/*\nsrc/empty/*  #   \n' >"$repo/sensors/test-first-exempt.txt"
printf '.factory/\n*.tmp\n' >"$repo/.gitignore"
git -C "$repo" add -A && git -C "$repo" commit -q -m "chore: seed"
cwd_json="$(json_str "$(native "$repo")")"

# expect <exit> <sensor> <label> <payload-json>
expect() {
  local want="$1" sensor="$2" label="$3" payload="$4" got
  got="$(cd "$repo" && printf '%s' "$payload" | bash "$here/$sensor" 2>/dev/null; echo $?)"
  got="${got##*$'\n'}"
  if [ "$got" = "$want" ]; then
    pass=$((pass + 1))
  else
    fail=$((fail + 1))
    echo "FAIL $sensor: $label (want exit $want, got $got)"
  fi
}
bash_cmd() { printf '{"tool_name":"Bash","cwd":%s,"tool_input":{"command":%s}}' "$cwd_json" "$(json_str "$1")"; }
edit_file() { printf '{"tool_name":"Write","cwd":%s,"tool_input":{"file_path":%s}}' "$cwd_json" "$(json_str "$(native "$repo/$1")")"; }
on_branch() { git -C "$repo" checkout -q "$1" 2>/dev/null || git -C "$repo" checkout -q -b "$1"; }

