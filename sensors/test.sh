# --- no JSON parser: sensors say they are off (exit 1, shown to the user) instead of exit 0.
nobin="$sandbox/nobin"
mkdir -p "$nobin"
for t in git cat dirname basename sed tr grep mktemp rm cp head cygpath; do
  real="$(command -v "$t" 2>/dev/null)" || continue
  printf '#!/bin/sh\nexec "%s" "$@"\n' "$real" >"$nobin/$t"
  chmod +x "$nobin/$t"
done
bash_path="$(command -v bash)"
noparser() {
  local want="$1" sensor="$2" label="$3" payload="$4" got
  got="$(cd "$repo" && printf '%s' "$payload" | PATH="$nobin" "$bash_path" "$here/$sensor" 2>/dev/null; echo $?)"
  got="${got##*$'\n'}"
  if [ "$got" = "$want" ]; then pass=$((pass + 1)); else fail=$((fail + 1)); echo "FAIL $sensor: $label (want exit $want, got $got)"; fi
}
noparser 1 block-protected-branch.sh "no parser: visible, not silent" "$(bash_cmd 'git commit -m x')"
noparser 1 verify-on-stop.sh "no parser on Stop: visible, never a block loop" "$(stop true)"
noparser 1 require-routed-subagent.sh "no parser: visible, not silent" "$(agent_call ',"subagent_type":"explorer"')"

# --- check-commit-msg (git hook: exit 1 rejects)
msg() {
  local want="$1" text="$2" got
  printf '%s\n' "$text" >"$sandbox/msg"
  bash "$here/check-commit-msg.sh" "$sandbox/msg" 2>/dev/null
  got=$?
  if [ "$got" = "$want" ]; then pass=$((pass + 1)); else fail=$((fail + 1)); echo "FAIL check-commit-msg: '$text' (want $want, got $got)"; fi
}
msg 0 "feat: add login"
msg 0 "fix(api)!: reject empty ids"
msg 0 "Merge branch 'feat/x'"
msg 0 "Merge pull request #12 from me/feat"
msg 0 "fixup! feat: add login"
msg 0 "squash! feat: add login"
msg 0 "amend! feat: add login"
msg 0 "$(printf 'feat: windows line ending\r')"
msg 0 "$(printf '# comment line\nchore: tidy')"
msg 1 "added stuff"
msg 1 "Merge whatever I want"
msg 1 "feat:missing space"
msg 1 "feat: $(printf 'x%.0s' $(seq 1 100))"

echo "sensors/test.sh: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
